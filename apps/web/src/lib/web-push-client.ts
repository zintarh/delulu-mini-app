"use client";

import { env } from "@/lib/env";

export type PushSupportState =
  | { state: "unsupported" }
  | { state: "needs_permission"; permission: NotificationPermission }
  | { state: "ready"; permission: NotificationPermission; subscribed: boolean };

function urlBase64ToUint8Array(base64String: string) {
  // VAPID public keys are commonly base64url, but can be pasted with
  // whitespace/PEM headers. Normalize, then decode without `atob`
  // (browser `atob` is strict and throws on certain non-padded inputs).
  let s = (base64String || "").trim();

  // PEM support: extract the base64 body if headers/footers exist.
  s = s
    .replace(/-----BEGIN [^-]+-----/g, "")
    .replace(/-----END [^-]+-----/g, "")
    .replace(/\s+/g, "");

  // Convert base64url -> base64 alphabet.
  s = s.replace(/-/g, "+").replace(/_/g, "/");

  // Defensive: remove anything outside the base64 alphabet.
  s = s.replace(/[^A-Za-z0-9+/=]/g, "");

  // Base64 decoder (base64url-safe) using bit accumulation.
  // This avoids `atob` strictness and works for padded/unpadded base64.
  const alphabet =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  let bits = 0;
  let bitLen = 0;
  const out: number[] = [];

  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === "=") continue; // padding doesn't contribute bits
    const val = alphabet.indexOf(ch);
    if (val < 0) continue; // skip unexpected chars defensively
    bits = (bits << 6) | val;
    bitLen += 6;
    while (bitLen >= 8) {
      bitLen -= 8;
      out.push((bits >> bitLen) & 0xff);
    }
  }

  const bytes = new Uint8Array(out);

  // VAPID public keys generated by web-push are typically 65 bytes
  // (uncompressed EC point with 0x04 prefix).
  if (bytes.length !== 65) {
    // Throw a descriptive error so the user can fix env.
    throw new Error(
      `Invalid VAPID public key: decoded length ${bytes.length} bytes (expected 65). ` +
        `Check NEXT_PUBLIC_VAPID_PUBLIC_KEY; it may be truncated or copied incorrectly.`
    );
  }

  return bytes;
}

/**
 * Wait briefly for the app SW to finish registering. On hard refresh the banner
 * can race ServiceWorkerRegister and see `subscribed: false` even when push is on.
 */
async function waitForPushRegistration(
  timeoutMs = 2500,
): Promise<ServiceWorkerRegistration | null> {
  if (!("serviceWorker" in navigator)) return null;

  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const reg = await navigator.serviceWorker.getRegistration("/");
    if (reg) {
      try {
        // Prefer an active worker when available; don't hang forever.
        return await Promise.race([
          navigator.serviceWorker.ready,
          new Promise<ServiceWorkerRegistration>((resolve) => {
            window.setTimeout(() => resolve(reg), 1200);
          }),
        ]);
      } catch {
        return reg;
      }
    }
    await new Promise((r) => window.setTimeout(r, 100));
  }

  return (await navigator.serviceWorker.getRegistration("/")) ?? null;
}

export async function getPushSupportState(): Promise<PushSupportState> {
  if (typeof window === "undefined") return { state: "unsupported" };
  if (!("serviceWorker" in navigator) || !("PushManager" in window)) {
    return { state: "unsupported" };
  }
  if (!("Notification" in window)) return { state: "unsupported" };

  const permission = Notification.permission;
  if (permission !== "granted") {
    return { state: "needs_permission", permission };
  }

  const reg = await waitForPushRegistration();
  const sub = reg ? await reg.pushManager.getSubscription() : null;
  return { state: "ready", permission, subscribed: Boolean(sub) };
}

export async function ensureServiceWorker(): Promise<ServiceWorkerRegistration> {
  const existing = await waitForPushRegistration(1500);
  if (existing) return existing;
  return navigator.serviceWorker.register("/sw.js", {
    scope: "/",
    updateViaCache: "none",
  });
}

function sameKey(a: ArrayBuffer | null | undefined, b: Uint8Array): boolean {
  if (!a) return false;
  const av = new Uint8Array(a);
  if (av.length !== b.length) return false;
  for (let i = 0; i < av.length; i++) if (av[i] !== b[i]) return false;
  return true;
}

/** Chrome/Edge/Brave throw AbortError "Registration failed - push service error"
 *  when the browser can't reach its push service (FCM). */
function isPushServiceError(err: unknown): boolean {
  if (!(err instanceof Error)) return false;
  return err.name === "AbortError" || /push service error/i.test(err.message);
}

function pushServiceErrorMessage(): string {
  const isBrave =
    typeof navigator !== "undefined" &&
    Boolean((navigator as Navigator & { brave?: unknown }).brave);
  return isBrave
    ? "Brave blocks push by default. Turn on \"Use Google services for push messaging\" in brave://settings/privacy, then try again."
    : "Your browser couldn't reach its push service. Check your connection, VPN or ad blocker and try again.";
}

async function getOrCreateSubscription(
  reg: ServiceWorkerRegistration,
  key: Uint8Array,
): Promise<PushSubscription> {
  const existing = await reg.pushManager.getSubscription();
  // A subscription made with an old VAPID key can't receive our pushes, and
  // subscribe() with a new key throws InvalidStateError until it's removed.
  if (existing) {
    if (sameKey(existing.options?.applicationServerKey, key)) return existing;
    await existing.unsubscribe().catch(() => {});
  }

  const opts: PushSubscriptionOptionsInit = {
    userVisibleOnly: true,
    applicationServerKey: key as BufferSource,
  };

  try {
    return await reg.pushManager.subscribe(opts);
  } catch (err) {
    if (err instanceof Error && err.name === "InvalidStateError") {
      const stale = await reg.pushManager.getSubscription();
      await stale?.unsubscribe().catch(() => {});
      return reg.pushManager.subscribe(opts);
    }
    if (!isPushServiceError(err)) throw err;
  }

  // Push service errors are often transient (FCM hiccup, SW just activated).
  await new Promise((r) => window.setTimeout(r, 1500));
  try {
    return await reg.pushManager.subscribe(opts);
  } catch (err) {
    if (isPushServiceError(err)) throw new Error(pushServiceErrorMessage());
    throw err;
  }
}

export async function subscribeToWebPush(address: string): Promise<void> {
  if (!env.NEXT_PUBLIC_VAPID_PUBLIC_KEY) {
    throw new Error("Push is not configured (missing VAPID public key).");
  }
  const reg = await ensureServiceWorker();

  const permission = await Notification.requestPermission();
  if (permission !== "granted") {
    throw new Error("Notifications permission not granted.");
  }

  const subscription = await getOrCreateSubscription(
    reg,
    urlBase64ToUint8Array(env.NEXT_PUBLIC_VAPID_PUBLIC_KEY),
  );

  const json = subscription.toJSON();

  const res = await fetch("/api/push/subscribe", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      address,
      subscription: {
        endpoint: subscription.endpoint,
        keys: json.keys,
      },
    }),
  });
  if (!res.ok) {
    const data = await res.json().catch(() => ({}));
    throw new Error(data?.error ?? "Failed to save push subscription.");
  }
}

export async function unsubscribeWebPush(address: string): Promise<void> {
  const reg = await navigator.serviceWorker.getRegistration("/");
  const sub = reg ? await reg.pushManager.getSubscription() : null;
  if (sub) {
    await sub.unsubscribe().catch(() => {});
  }
  await fetch("/api/push/unsubscribe", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ address, endpoint: sub?.endpoint ?? null }),
  }).catch(() => {});
}

